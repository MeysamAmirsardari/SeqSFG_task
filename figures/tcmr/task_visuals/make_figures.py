# Analytic envelopes of the actual generator, before gating, with the same common gain.
f,axs=plt.subplots(1,2,figsize=(10,4.4),sharey=True);f.subplots_adjust(left=.1,right=.97,bottom=.2,top=.79,wspace=.18)
t=np.arange(2400)/48000;gate=envelope(t,.05,.01)
for ax,co,title in zip(axs,[True,False],['Comodulated','Independent']):
 xs=band_bursts(cfg,np.random.default_rng(37),co)
 for b,x in enumerate(xs):
  # Recover the baseband envelope from the full spectral construction (avoid cropped Hilbert edges).
  rng=np.random.default_rng(37);k=np.arange(-10,11);shared=rng.normal(size=21)+1j*rng.normal(size=21)
  specs=[]
  for bb in range(5):specs.append(shared if co else rng.normal(size=21)+1j*rng.normal(size=21))
  e=np.abs(np.exp(2j*np.pi*t[:,None]*k)@specs[b])/np.sqrt(21)*gate
  ax.plot(t*1000,b+e*.20,c='.15',lw=1.4)
 ax.set_xlim(0,50);ax.set_ylim(-.15,5);ax.set_xticks([0,25,50]);ax.set_yticks(range(5),['250','500','1000','2000','4000']);clean(ax);ax.set_xlabel('Time from burst onset (ms)');ax.set_title(title,loc='left',pad=14,fontsize=16)
axs[0].set_ylabel('Band (Hz)');f.text(.1,.94,'Noise envelopes',fontsize=19)
f.text(.1,.055,'One generated burst  ·  Common amplitude scale  ·  20 Hz bandwidth  ·  10 ms onset and offset ramps',fontsize=11)
save(f,'03_envelopes')

