def clean(ax):
 ax.spines[['top','right','left']].set_visible(False);ax.tick_params(axis='y',length=0)
def raster(ax,tr,iv,relative=True,signal=True):
 base=tr.interval_on_s[iv] if relative else 0
 t0=tr.target_on_s[iv]-cfg.n_precursors*cfg.noi_ms/1000
 for j in range(6):
  for b in range(5):
   off=0 if j==5 else (tr.slots[iv][j][b]*tr.dt_ms if tr.slots else 0)
   on=t0+j*.2+off/1000-base
   ax.add_patch(Rectangle((on,b-.16),.05,.32,fc='.67',ec='none'))
 if signal and iv+1==tr.signal_interval:
  on=tr.target_on_s[iv]-base;ax.plot([on,on+.05],[2,2],c='black',lw=3)
 ax.set_ylim(-.65,4.85);ax.set_yticks(range(5),['250','500','1000','2000','4000']);clean(ax)

# Exact trial timing, 20-ms example generated by the task.
